// Letzter Treffer in der Liste gewinnt bei Überschneidungen (spezifischere
// Ausnahmen stehen nach den breiten Bereichen).
function getBundeslandForPlz(plz) {
  if (!plz) return null;
  const num = parseInt(String(plz).replace(/\D/g, ''), 10);
  if (!num) return null;
  let result = null;
  for (const r of RANGES) {
    if (num >= r.from && num <= r.till) result = r.region;
  }
  return result;
}

